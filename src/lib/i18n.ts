export type MessageKey = keyof typeof en;

const dict: Record<Locale, Record<MessageKey, string>> = { en, nb };

export const DEFAULT_LOCALE: Locale = "nb";
export const STORAGE_KEY = "control.locale";

export function isLocale(v: unknown): v is Locale {
  return v === "nb" || v === "en";
}

export function dateLocale(locale: Locale) {
  return locale === "nb" ? "nb-NO" : "en-GB";
}

export function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] == null ? `{${k}}` : String(vars[k]),
  );
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  return interpolate(dict[locale][key] ?? dict.en[key] ?? key, vars);
}
